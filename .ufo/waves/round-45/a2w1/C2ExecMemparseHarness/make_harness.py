def extract(path, first, last):
    with open(path, "r", encoding="utf-8", newline="") as f:
        lines = f.read().split("\n")
    return "\n".join(lines[first - 1:last])


def main():
    out = os.environ.get("HARNESS_OUT", os.path.join(HERE, "harness.c"))
    body = []
    manifest = []
    for name, path, first, last, prov in BLOCKS:
        text = extract(path, first, last)
        if not text.strip():
            sys.exit("empty block %s" % name)
        body.append("/* @@BEGIN %s @@ %s */\n%s\n/* @@END %s @@ */\n"
                    % (name, prov, text, name))
        with open(path, "rb") as f:
            manifest.append("%s  %s  [%s:%d-%d]"
                            % (hashlib.sha256(f.read()).hexdigest(), path, prov, first, last))
    src = SCAFFOLD.replace("@@BLOCKS@@", "\n".join(body))
    with open(out, "w", encoding="utf-8", newline="") as f:
        f.write(src)
    mpath = os.path.join(os.path.dirname(out), "manifest.sha256")
    with open(mpath, "w", encoding="utf-8") as f:
        f.write("\n".join(manifest) + "\n")
    print("wrote %s (%d bytes, %d blocks)" % (out, len(src), len(BLOCKS)))
    print("wrote %s" % mpath)


if __name__ == "__main__":
    main()
