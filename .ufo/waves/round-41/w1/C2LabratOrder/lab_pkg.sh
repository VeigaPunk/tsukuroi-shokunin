#!/bin/bash
# End-to-end: makepkg's own listing -> .MTREE -> package, with a top-level
# name '-dash' whose first byte (0x2D) is below '.' (0x2E). Read-only pacman
# queries on the scratch package (-Qp/-Qip/-Qlp); no transactions.
set -u
B=/fast/scratch/hyaku/tsukuroi-r41/C2LabratOrder
P=$B/treeE; rm -rf "$P"; mkdir -p "$P"; cd "$P" || exit 1
mkdir -p -- usr/bin A _x ./-lib
printf 'x' > usr/bin/hello; printf 'x' > A/data; printf 'x' > _x/f
printf 'x' > -dash; printf 'x' > -lib/child

list_package_files() {
	(
		export LC_COLLATE=C
		shopt -s dotglob globstar
		printf '%s\0' **/*
	)
}
cat > .PKGINFO <<'EOF'
# Generated by makepkg 7.1.0
pkgname = demo
pkgbase = demo
pkgver = 1-1
pkgdesc = ordering lab
url = none
builddate = 1700000000
packager = lab <lab@example.invalid>
size = 12
arch = x86_64
EOF
printf '#buildinfo\nformat = 2\n' > .BUILDINFO
printf 'post_install() { :; }\n' > .INSTALL

echo "## body order (bash $BASH_VERSION):"
list_package_files | tr '\0' '\n' | nl -ba
echo "## generating .MTREE exactly as create_package:617-620"
list_package_files | LANG=C bsdtar -cnf - --format=mtree \
	--options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' \
	--null --files-from - --exclude .MTREE | gzip -c -f -n > .MTREE
touch -d @1700000000 .MTREE
echo "## .MTREE member names only (escape check for '-' and dot files):"
zcat .MTREE | sed -n '1,4p'
echo "## creating package (bsdtar | zstd), exactly as create_package:625-626"
list_package_files | LANG=C bsdtar --no-fflags -cnf - --null --files-from - | zstd -q -c > "$B/demo-1-1-x86_64.pkg.tar.zst"
echo "## archive member order (bsdtar -tf), head -8:"
bsdtar -tf "$B/demo-1-1-x86_64.pkg.tar.zst" | head -8
echo "## full archive member order:"
bsdtar -tf "$B/demo-1-1-x86_64.pkg.tar.zst" | nl -ba
echo "## pacman -Qp (partial load):"
pacman -Qp "$B/demo-1-1-x86_64.pkg.tar.zst" --dbpath "$B/emptydb" 2>&1; echo "rc=$?"
install -d "$B/emptydb"
echo "## pacman -Qp with empty scratch dbpath:"
pacman -Qp "$B/demo-1-1-x86_64.pkg.tar.zst" --dbpath "$B/emptydb" 2>&1; echo "rc=$?"
echo "## pacman -Qip:"
pacman -Qip "$B/demo-1-1-x86_64.pkg.tar.zst" --dbpath "$B/emptydb" 2>&1 | head -20; echo "rc=$?"
echo "## pacman -Qlp (full load -> file list):"
pacman -Qlp "$B/demo-1-1-x86_64.pkg.tar.zst" --dbpath "$B/emptydb" 2>&1; echo "rc=$?"
echo "## pacman -Qkk needs a db entry; package is not installed, skipping (no transaction)."
